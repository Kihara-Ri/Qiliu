import { access, appendFile, readFile } from "node:fs/promises";
import { existsSync, mkdirSync } from "node:fs";
import { homedir } from "node:os";
import { join } from "node:path";
import { spawnSync } from "node:child_process";

// Configures release-APK signing on the generated Android project.
//
// With ANDROID_KEYSTORE_BASE64 (CI secret) the restored upload keystore is
// used. Without it, the release build is signed with the standard Android
// debug keystore so the APK stays installable for testing — but compiled in
// release mode, instead of shipping the 200+ MB debug-native library that
// slow-loading debug builds produce on real devices.
const gradlePath = new URL("../src-tauri/gen/android/app/build.gradle.kts", import.meta.url);
const current = await readFile(gradlePath, "utf8");
if (current.includes("QILIU_RELEASE_SIGNING")) process.exit(0);

const debugKeystore = process.env.ANDROID_DEBUG_KEYSTORE || join(homedir(), ".android", "debug.keystore");

function ensureDebugKeystore() {
  if (existsSync(debugKeystore)) return;
  mkdirSync(join(debugKeystore, ".."), { recursive: true });
  const result = spawnSync(
    "keytool",
    [
      "-genkeypair",
      "-keystore", debugKeystore,
      "-storepass", "android",
      "-keypass", "android",
      "-alias", "androiddebugkey",
      "-keyalg", "RSA",
      "-keysize", "2048",
      "-validity", "10000",
      "-dname", "CN=Android Debug,O=Android,C=US",
    ],
    { stdio: "inherit" },
  );
  if (result.status !== 0) {
    throw new Error(`无法创建调试密钥库 ${debugKeystore}，请确认 keytool 可用。`);
  }
}

const signingLines = [];
if (process.env.ANDROID_KEYSTORE_PATH || process.env.ANDROID_KEYSTORE_BASE64) {
  for (const name of ["ANDROID_KEYSTORE_PATH", "ANDROID_KEY_ALIAS", "ANDROID_KEY_PASSWORD", "ANDROID_STORE_PASSWORD"]) {
    if (!process.env[name]) throw new Error(`缺少 Android 签名环境变量：${name}`);
  }
  await access(process.env.ANDROID_KEYSTORE_PATH);
  // Secrets stay in the environment instead of being written to disk.
  signingLines.push(
    "            storeFile = file(System.getenv(\"ANDROID_KEYSTORE_PATH\"))",
    "            storePassword = System.getenv(\"ANDROID_STORE_PASSWORD\")",
    "            keyAlias = System.getenv(\"ANDROID_KEY_ALIAS\")",
    "            keyPassword = System.getenv(\"ANDROID_KEY_PASSWORD\")",
  );
} else {
  ensureDebugKeystore();
  console.log(`未配置上传密钥，release 构建将使用调试密钥签名：${debugKeystore}`);
  const literal = debugKeystore.replaceAll("\\", "/");
  signingLines.push(
    `            storeFile = file("${literal}")`,
    '            storePassword = "android"',
    '            keyAlias = "androiddebugkey"',
    '            keyPassword = "android"',
  );
}

await appendFile(
  gradlePath,
  `

// QILIU_RELEASE_SIGNING — generated by scripts/configure-android-signing.mjs
android {
    signingConfigs {
        create("qiliuRelease") {
${signingLines.join("\n")}
        }
    }
    buildTypes.getByName("release") {
        signingConfig = signingConfigs.getByName("qiliuRelease")
    }
}
`,
);

console.log("已配置 Android release 签名");
